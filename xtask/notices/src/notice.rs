//! Resolve bundled licenses and render deterministic third-party notices.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write as _,
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result, ensure};
use comfit_internal::{grammar::Registry, is_license_filename};

use crate::config::{Component, Config, Package};

struct Notice {
    component: Component,
    files: BTreeMap<String, String>,
}

pub(crate) fn generate(root: &Path, config: &Config, package: &Package) -> Result<String> {
    let mut notices = Vec::new();
    let queries = package.components.iter().any(|name| name == "queries");
    let mut names = BTreeSet::new();

    for name in &package.components {
        if name == "grammars" {
            notices.extend(grammar_notices(root, config)?);
            continue;
        }

        if name == "queries" {
            names.insert("nvim-treesitter");
        } else {
            names.insert(name.as_str());
        }
    }

    for name in names {
        let component = config
            .components
            .iter()
            .find(|component| component.name == name)
            .with_context(|| format!("missing notice metadata for {name}"))?;
        let mut files = BTreeMap::new();
        ensure!(!component.files.is_empty(), "no license files for {name}");

        for path in &component.files {
            files.insert(path.clone(), read_license(&root.join(path))?);
        }

        notices.push(Notice {
            component: component.clone(),
            files,
        });
    }

    notices.sort_by(|left, right| left.component.name.cmp(&right.component.name));
    let mut output = String::from(
        "Third-party notices\n\nComfit is MIT-licensed. The bundled components listed below retain their\nrespective licenses. Original license and notice texts are reproduced unchanged.\n\nGenerated by cargo notices build from registry/notices.toml and prepared sources.\n\n",
    );

    for Notice { component, files } in notices {
        writeln!(output, "Component: {}", component.name)?;
        writeln!(output, "Source: {}", component.source)?;

        if let Some(revision) = component.revision {
            writeln!(output, "Revision: {revision}")?;
        }

        if let Some(version) = component.version {
            writeln!(output, "Version: {version}")?;
        }

        writeln!(output, "License: {}", component.license)?;
        writeln!(output, "Included material: {}\n", component.material)?;

        if files.is_empty() {
            writeln!(
                output,
                "No upstream license file provided. Declared license:\n"
            )?;
            let license = match component.license.as_str() {
                "MIT" => "The MIT License (MIT)",
                license => license,
            };
            writeln!(output, "{license}\n")?;
        }

        for (path, text) in files {
            writeln!(output, "--- Original {path} ---\n")?;
            output.push_str(&text);

            if !text.ends_with('\n') {
                output.push('\n');
            }

            output.push('\n');
        }
    }

    if queries {
        output.push_str("Query source attribution\n\n");
        let mut paths = Vec::new();

        for entry in fs::read_dir(root.join("queries"))? {
            let entry = entry?;

            if entry.file_type()?.is_dir() {
                let path = entry.path().join("README.md");
                ensure!(path.is_file(), "missing attribution: {}", path.display());
                paths.push(path);
            }
        }

        paths.sort();

        for path in paths {
            writeln!(
                output,
                "--- {} ---\n",
                path.strip_prefix(root)?
                    .to_string_lossy()
                    .replace('\\', "/")
            )?;
            output.push_str(&read_license(&path)?);
            output.push('\n');
        }
    }

    Ok(output)
}

fn grammar_notices(root: &Path, config: &Config) -> Result<Vec<Notice>> {
    let source = fs::read_to_string(root.join("registry/languages.toml"))?;
    let data = root.join("crates/comfit_grammars/data");
    let prepared = fs::read_to_string(data.join("languages.toml"))
        .context("run cargo grammars update before generating grammar notices")?;
    ensure!(
        toml::from_str::<toml::Value>(&source)? == toml::from_str::<toml::Value>(&prepared)?,
        "prepared grammar metadata is outdated, run cargo grammars update"
    );
    let registry: Registry = toml::from_str(&source)?;
    let mut groups: BTreeMap<_, Notice> = BTreeMap::new();

    for (id, grammar) in &registry.grammars {
        let license = config
            .grammar_licenses
            .get(id)
            .with_context(|| format!("missing SPDX license for grammar {id}"))?;
        let directory = data.join("grammars").join(id);
        let mut paths = license_paths(&directory)?;

        if grammar.path != "." {
            paths.extend(license_paths(&directory.join(&grammar.path))?);
        }

        let key = (&grammar.repository, grammar.revision.as_str());
        let notice = groups.entry(key).or_insert_with(|| Notice {
            component: Component {
                name: grammar.repository.rsplit('/').next().unwrap().to_owned(),
                source: grammar.repository.clone(),
                revision: Some(grammar.revision.as_str().to_owned()),
                version: None,
                license: license.clone(),
                material: String::from("Tree-sitter parsers for grammars:"),
                files: Vec::new(),
            },
            files: BTreeMap::new(),
        });
        ensure!(
            notice.component.license == *license,
            "conflicting grammar licenses for {id}"
        );
        write!(notice.component.material, " {id}")?;

        for path in paths {
            let text = read_license(&path)?;

            if !notice.files.values().any(|existing| existing == &text) {
                notice.files.insert(
                    path.strip_prefix(root)?
                        .to_string_lossy()
                        .replace('\\', "/"),
                    text,
                );
            }
        }
    }

    Ok(groups.into_values().collect())
}

fn license_paths(directory: &Path) -> Result<Vec<PathBuf>> {
    let mut paths = Vec::new();

    for entry in
        fs::read_dir(directory).with_context(|| format!("reading {}", directory.display()))?
    {
        let entry = entry?;
        let name = entry.file_name();

        if is_license_filename(&name.to_string_lossy()) {
            collect_files(&entry.path(), &mut paths)?;
        }
    }

    paths.sort();
    Ok(paths)
}

fn collect_files(path: &Path, output: &mut Vec<PathBuf>) -> Result<()> {
    let metadata = fs::symlink_metadata(path)?;
    ensure!(
        !metadata.is_symlink(),
        "license path is a symlink: {}",
        path.display()
    );

    if metadata.is_dir() {
        for entry in fs::read_dir(path)? {
            collect_files(&entry?.path(), output)?;
        }
    } else if metadata.is_file() {
        output.push(path.to_owned());
    }

    Ok(())
}

fn read_license(path: &Path) -> Result<String> {
    let text = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    ensure!(
        !text.trim().is_empty(),
        "empty license or attribution: {}",
        path.display()
    );
    Ok(text)
}
